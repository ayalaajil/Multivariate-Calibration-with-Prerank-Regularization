def parse_pce(latex_str):
    res = []
    lines = latex_str.strip().split('\n')
    for line in lines:
        if '&' in line:
            # Extract numbers after & and before ( or \,
            matches = re.findall(r'&\s*\$?\s*(\d+\.\d+)', line)
            res.append([float(m) for m in matches])
    return np.array(res)

